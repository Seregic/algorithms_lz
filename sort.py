#введем библиотеку случайных чисел
import random 
#введим массив из 100 случайных чисел от 1 до 1000000  
a = [random.randint(1,1000000) for i in range(100)]
#присвоим массив a новой переменной b для еще дальнейшей сортировки выбором 
b = a.copy()
#зададим счетчик перестановок при сортировке пузырьком
k1 = 0
#делаем сортировку пузырьком
l=1
while(l==1):
    l=0
    for i in range(0,len(a)-1):
      if a[i]<a[i+1] :
        swap = a[i]
        a[i] = a[i+1]
        a[i+1] = swap
        l=1
        k1+=1
        print("Промежуточный результат сортировки пузырьком: " ,a)
      else:
        print("Промежуточный результат сортировки пузырьком: " ,a)

#зададим счетчик перестановок при сортировке пузырьком
k2 = 0
#делаем сортировку выбором
c = []
while len(b) > 0 :
   max = b[0]
   for i in range(0,len(b)):
      if b[i] > max:
         max = b[i]
   k2+=1
   c.append(max)
   b.remove(max)
   print("Промежуточный результат новой коллекции сортировки выбором: ",c)
   print("Промежуточный результат старой коллекции сортировки выбором: ",b)
#выводим всё
print("Результат сортировки пузырьком: " ,a)
print("Количество перестановок сортировкой пузырьком: " ,k1)
print("Результат сортировки выбором: ",c)
print("Количество перестановок сортировкой выбором: " ,k2)