#введем библиотеку случайных чисел
import random
#введим массив из 100 случайных чисел от 1 до 1000000 без дубликатов
a = random.sample(range(0,1000000),100)
#выводим коллекцию, чтобы ,смотря на неё, определить, индекс какого элемента мы хотим найти
print (a)
e = int(input("Введите значение элемента, индекс которого хотите найти : "))
#введем переменную для линейного поиска, по значению которой будем определять, нашли мы элемент или нет
f1 = 0
#введем счетчик сравнений для линейного поиска
k1 = 0
#оформляем линейный поиск
for i in range(0,len(a)) :
    k1+=1
    if a[i] == e:
        print ("Индекс искомого элемента равен: ",i)
        print("Количество сравнений при линейном поиске: ", k1)
        f1 = 1
        break
#проверка на обнаружение элемента
if f1 == 0:
    print("Такого элемента здесь нет")

#отсортировываем выбором коллекцию для бинарного поиска
b = []
while len(a) > 0 :
   min = a[0]
   for i in range(0,len(a)):
      if a[i] < min:
         min = a[i]
   b.append(min)
   a.remove(min)
print("Отсортированный массив a : ", b)
#введем счетчик сравнений для бинарного поиска
k2 = 0
#оформляем бинарный поиск
f = 0
l = len(b)-1
index = -1
while (f<=l) and (index==-1):
    k2+=1
    mid = (f+l)//2
    if b[mid] == e:
      index = mid
    else: 
        if b[mid] > e :
           l = mid - 1
        else :
           f = mid + 1

print ("Индекс искомого элемента равен: ",index)
print ("Количество сравнений при бинарном поиске: ", k2)
